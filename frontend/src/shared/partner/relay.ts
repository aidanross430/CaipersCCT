// The relay envelope: the small set of frames the hosted relay itself understands. Every
// ToProctor / ToParticipant message from protocol.ts travels inside a 'data' frame as an opaque
// string, so the relay never parses (or depends on) the app protocol.
// Shared by main (participant), the proctor client and relay/, so no Node or DOM imports here.
import { type ParseResult } from '../check'
//
//   participant app          relay                 proctor app
//        |-- hello ------------>|                        |
//        |<-- ready ------------|                        |
//        |                      |<------------ hello ----|
//        |<-- peer: joined -----|------ ready ---------->|
//        |<-- data(handshake) --|<----- data(handshake) -|   pairing stays end to end:
//        |--- data(welcome) --->|------ data(welcome) -->|   the participant app decides
//        |--- data(view) ------>|------ data(view) ----->|

// RELAY_VERSION
//   Bumped whenever the shape of an envelope frame changes. Separate from PROTOCOL_VERSION:
//   the relay checks this one in 'hello'; only the participant app checks PROTOCOL_VERSION
export const RELAY_VERSION = 1

// The first frame must arrive within this long, or the relay closes the socket
export const HELLO_TIMEOUT_MS = 5_000

// Same ceiling as lanHost's MAX_PAYLOAD_BYTES. A whole frame, envelope included, must fit
export const MAX_FRAME_BYTES = 16 * 1024

// Room codes
//   6 characters, no 0/O, 1/I/L, so a code read aloud or off a screen can't be mistyped.
//   ~31^6 ≈ 887 million codes, single-use per app run, plus attempt limits on the relay.
//   Generated by the participant app (main, with crypto.randomInt), never by the relay. If the
//   relay answers 'room-taken', the participant generates a new code (and claim) and says hello
//   again, up to MAX_ROOM_CODE_ATTEMPTS times before reporting the relay as unusable
export const ROOM_CODE_ALPHABET = '23456789ABCDEFGHJKMNPQRSTUVWXYZ'
export const ROOM_CODE_LENGTH = 6
// A collision is ~1 in 887 million per open room, so a second one in a row means something
// else is wrong (e.g. a relay bug answering 'room-taken' to everything)
export const MAX_ROOM_CODE_ATTEMPTS = 5

// Room claim
//   A random secret the participant app makes alongside each room code and sends in every
//   participant hello. It's how the relay tells "the same participant reconnecting after a drop"
//   (same claim: reclaims the room, replacing the old socket) from "a different participant app
//   that happened to pick the same code" (different claim: refused 'room-taken'). Never shown on
//   screen or sent to the proctor. Format left to the relayClient (e.g. 32 hex characters)
export const MIN_CLAIM_LENGTH = 16

// Case-insensitive on input: the proctor UI should upper-case before sending, and this is the
// check both the relay and validate.ts's handshake use
export function isRoomCode(code: unknown): code is string {
  return (
    typeof code === 'string' &&
    code.length === ROOM_CODE_LENGTH &&
    [...code].every((c) => ROOM_CODE_ALPHABET.includes(c))
  )
}

export type RelayRole = 'participant' | 'proctor'

// Why the relay turned a client away. A code (not just text) so each client can show its own
// wording, e.g. the proctor UI says "check the code on the participant's screen" for no-such-room
export type RefusedReason =
  | 'bad-hello'          // first frame missing, late, malformed, or not a hello
  | 'version-mismatch'   // relayVersion isn't RELAY_VERSION
  | 'bad-token'          // lab access token wrong
  | 'no-such-room'       // proctor joined a code no participant has opened
  | 'room-taken'         // participant hello for a room held under a different claim:
                         // the participant regenerates its code and tries again
  | 'too-many-attempts'  // this address failed too often recently
  | 'server-full'        // MAX_ROOMS reached

// ToRelay (client -> relay)
// Hellobase is used as the framework for handshakes. Information that is sent whether or not the joining
// client is of type participant or proctor
export type HelloBase = { type: 'hello'; relayVersion: number; room: string; token: string }
export type ToRelay =
  | (HelloBase & { role: 'participant'; claim: string })  // Opens or reclaims the room with the matching claim
  | (HelloBase & { role: 'proctor' })                     // Joins the designated room.
  | { type: 'data'; payload: string }                     // A protocol.ts message sent to the partner

// FromRelay (relay -> client)
export type FromRelay =
  | { type: 'ready'; peerPresent: boolean }                     // hello is accepted, peerPresent is true if partner is in room
  | { type: 'refused'; reason: RefusedReason; detail: string }  // Relay closes the socket if connection is refused
  | { type: 'peer'; state: 'joined' | 'left' }                  // whether the partner joined or left
  | { type: 'data'; payload: string }                           // a protocol.ts message from your partner (contains live view/messages)

